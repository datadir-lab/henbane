// Command gen regenerates data_gen.go from the AI crawlers' official published
// IP-range feeds. Run it with `go generate ./internal/detect/crawlerips/...`
// (or `go run ./internal/detect/crawlerips/gen`) whenever the bundled snapshot
// should be refreshed. It fetches each vendor's own JSON feed — never a
// third-party aggregator — so the bundled data is authoritative.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"net/http"
	"net/netip"
	"os"
	"sort"
	"time"
)

// source is one crawler identity: a display name, the User-Agent tokens a
// genuine instance presents, and the vendor's own IP-range feed.
type source struct {
	name string
	uas  []string
	url  string
}

// sources lists the AI crawlers that publish verifiable IP ranges but have no
// reverse DNS (so the FCrDNS good-bot verifier cannot confirm them). Each URL is
// the vendor's first-party feed. OAI-AdsBot is deliberately omitted: it is ad
// infrastructure, not a content crawler an operator typically wants allow-listed.
var sources = []source{
	{"gptbot", []string{"gptbot"}, "https://openai.com/gptbot.json"},
	{"chatgpt-user", []string{"chatgpt-user"}, "https://openai.com/chatgpt-user.json"},
	{"oai-searchbot", []string{"oai-searchbot"}, "https://openai.com/searchbot.json"},
	// Anthropic publishes one shared list for all of its bots.
	{"anthropic", []string{"claudebot", "claude-searchbot", "claude-user"}, "https://claude.com/crawling/bots.json"},
	{"perplexitybot", []string{"perplexitybot"}, "https://www.perplexity.ai/perplexitybot.json"},
	{"perplexity-user", []string{"perplexity-user"}, "https://www.perplexity.ai/perplexity-user.json"},
}

// feed is the common schema every vendor uses (Google's well-known bot-range
// format): a creation timestamp and a list of CIDR prefixes.
type feed struct {
	CreationTime string `json:"creationTime"`
	Prefixes     []struct {
		IPv4Prefix string `json:"ipv4Prefix"`
		IPv6Prefix string `json:"ipv6Prefix"`
	} `json:"prefixes"`
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

func run() error {
	client := &http.Client{Timeout: 30 * time.Second}

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by gen/main.go; DO NOT EDIT.\n")
	fmt.Fprintf(&buf, "// Source: each AI vendor's own published IP-range feed. Regenerate with\n")
	fmt.Fprintf(&buf, "// `go generate ./internal/detect/crawlerips/...`.\n\n")
	fmt.Fprintf(&buf, "package crawlerips\n\n")
	fmt.Fprintf(&buf, "// bundledSource is one crawler's published identity: User-Agent tokens and\n")
	fmt.Fprintf(&buf, "// the CIDR prefixes its requests legitimately originate from.\n")
	fmt.Fprintf(&buf, "type bundledSource struct {\n\tname  string\n\tuas   []string\n\tcidrs []string\n}\n\n")
	fmt.Fprintf(&buf, "var bundled = []bundledSource{\n")

	total := 0
	for _, s := range sources {
		cidrs, created, err := fetch(client, s.url)
		if err != nil {
			return fmt.Errorf("%s: %w", s.name, err)
		}
		total += len(cidrs)
		fmt.Fprintf(&buf, "\t{\n")
		fmt.Fprintf(&buf, "\t\tname: %q,\n", s.name)
		fmt.Fprintf(&buf, "\t\t// %s — %s, %d prefixes as of %s\n", s.url, s.name, len(cidrs), created)
		fmt.Fprintf(&buf, "\t\tuas: %#v,\n", s.uas)
		fmt.Fprintf(&buf, "\t\tcidrs: []string{\n")
		for _, c := range cidrs {
			fmt.Fprintf(&buf, "\t\t\t%q,\n", c)
		}
		fmt.Fprintf(&buf, "\t\t},\n\t},\n")
		fmt.Printf("gen: %-16s %3d prefixes (%s)\n", s.name, len(cidrs), s.url)
	}
	fmt.Fprintf(&buf, "}\n")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("format: %w", err)
	}
	if err := os.WriteFile("data_gen.go", formatted, 0o644); err != nil {
		return err
	}
	fmt.Printf("gen: wrote data_gen.go (%d crawlers, %d prefixes)\n", len(sources), total)
	return nil
}

// fetch downloads one feed and returns its canonical, sorted, de-duplicated CIDR
// strings. Every prefix is parsed and re-emitted in masked form so the bundled
// data is guaranteed valid and produces stable diffs across regenerations.
func fetch(client *http.Client, url string) (cidrs []string, created string, err error) {
	resp, err := client.Get(url)
	if err != nil {
		return nil, "", err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, "", fmt.Errorf("status %d", resp.StatusCode)
	}
	var f feed
	if err := json.NewDecoder(resp.Body).Decode(&f); err != nil {
		return nil, "", err
	}
	seen := map[string]bool{}
	for _, p := range f.Prefixes {
		raw := p.IPv4Prefix
		if raw == "" {
			raw = p.IPv6Prefix
		}
		if raw == "" {
			continue
		}
		pfx, err := netip.ParsePrefix(raw)
		if err != nil {
			return nil, "", fmt.Errorf("bad prefix %q: %w", raw, err)
		}
		canon := pfx.Masked().String()
		if !seen[canon] {
			seen[canon] = true
			cidrs = append(cidrs, canon)
		}
	}
	if len(cidrs) == 0 {
		return nil, "", fmt.Errorf("no prefixes in feed")
	}
	sort.Strings(cidrs)
	return cidrs, f.CreationTime, nil
}
