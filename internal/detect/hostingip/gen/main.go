// Command gen regenerates data_gen.go from the major cloud providers' own
// published IP-range feeds. Run it with `go generate ./internal/detect/hostingip/...`
// (or `go run ./internal/detect/hostingip/gen`) to refresh the bundled snapshot.
// It fetches each provider's first-party feed, never a third-party aggregator, so
// the bundled data is authoritative. Prefixes are deduplicated, contained prefixes
// are dropped (leaving a non-overlapping set so the runtime match is a simple binary
// search), and the result is sorted for stable diffs.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"net/http"
	"net/netip"
	"os"
	"sort"
	"time"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

func run() error {
	client := &http.Client{Timeout: 60 * time.Second}

	var all []netip.Prefix
	aws, err := fetchAWS(client)
	if err != nil {
		return fmt.Errorf("aws: %w", err)
	}
	fmt.Printf("gen: aws  %5d prefixes\n", len(aws))
	all = append(all, aws...)

	gcp, err := fetchGCP(client)
	if err != nil {
		return fmt.Errorf("gcp: %w", err)
	}
	fmt.Printf("gen: gcp  %5d prefixes\n", len(gcp))
	all = append(all, gcp...)

	v4 := reduce(all, true)
	v6 := reduce(all, false)

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by gen/main.go; DO NOT EDIT.\n")
	fmt.Fprintf(&buf, "// Source: the cloud providers' own published IP-range feeds (AWS, GCP).\n")
	fmt.Fprintf(&buf, "// Regenerate with `go generate ./internal/detect/hostingip/...`.\n")
	fmt.Fprintf(&buf, "// %d IPv4 and %d IPv6 prefixes, deduplicated and non-overlapping, as of %s.\n\n",
		len(v4), len(v6), time.Now().UTC().Format("2006-01-02"))
	fmt.Fprintf(&buf, "package hostingip\n\n")
	writeConst(&buf, "bundledV4", v4)
	writeConst(&buf, "bundledV6", v6)

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("format: %w", err)
	}
	if err := os.WriteFile("data_gen.go", formatted, 0o644); err != nil {
		return err
	}
	fmt.Printf("gen: wrote data_gen.go (%d v4, %d v6)\n", len(v4), len(v6))
	return nil
}

func writeConst(buf *bytes.Buffer, name string, prefixes []netip.Prefix) {
	fmt.Fprintf(buf, "// %s is one CIDR per line (sorted, non-overlapping).\n", name)
	fmt.Fprintf(buf, "const %s = `", name)
	for _, p := range prefixes {
		fmt.Fprintf(buf, "%s\n", p.String())
	}
	fmt.Fprintf(buf, "`\n\n")
}

// reduce keeps the prefixes of the requested family, deduplicates them, drops any
// prefix contained in another, and sorts the result. A non-overlapping, sorted set
// lets the runtime use a binary search for membership.
func reduce(in []netip.Prefix, wantV4 bool) []netip.Prefix {
	seen := map[netip.Prefix]bool{}
	var out []netip.Prefix
	for _, p := range in {
		p = p.Masked()
		if p.Addr().Is4() != wantV4 || seen[p] {
			continue
		}
		seen[p] = true
		out = append(out, p)
	}
	// Sort by address, then by prefix length ascending, so a container is visited
	// before anything it contains.
	sort.Slice(out, func(i, j int) bool {
		if c := out[i].Addr().Compare(out[j].Addr()); c != 0 {
			return c < 0
		}
		return out[i].Bits() < out[j].Bits()
	})
	kept := out[:0]
	for _, p := range out {
		if n := len(kept); n > 0 && kept[n-1].Contains(p.Addr()) {
			continue // contained in the last kept prefix; drop it
		}
		kept = append(kept, p)
	}
	return kept
}

// --- AWS: https://ip-ranges.amazonaws.com/ip-ranges.json ---

func fetchAWS(client *http.Client) ([]netip.Prefix, error) {
	var doc struct {
		Prefixes []struct {
			IPPrefix string `json:"ip_prefix"`
		} `json:"prefixes"`
		IPv6Prefixes []struct {
			IPv6Prefix string `json:"ipv6_prefix"`
		} `json:"ipv6_prefixes"`
	}
	if err := fetchJSON(client, "https://ip-ranges.amazonaws.com/ip-ranges.json", &doc); err != nil {
		return nil, err
	}
	var out []netip.Prefix
	for _, p := range doc.Prefixes {
		out = appendPrefix(out, p.IPPrefix)
	}
	for _, p := range doc.IPv6Prefixes {
		out = appendPrefix(out, p.IPv6Prefix)
	}
	return out, nil
}

// --- GCP: https://www.gstatic.com/ipranges/cloud.json ---

func fetchGCP(client *http.Client) ([]netip.Prefix, error) {
	var doc struct {
		Prefixes []struct {
			IPv4Prefix string `json:"ipv4Prefix"`
			IPv6Prefix string `json:"ipv6Prefix"`
		} `json:"prefixes"`
	}
	if err := fetchJSON(client, "https://www.gstatic.com/ipranges/cloud.json", &doc); err != nil {
		return nil, err
	}
	var out []netip.Prefix
	for _, p := range doc.Prefixes {
		out = appendPrefix(out, p.IPv4Prefix)
		out = appendPrefix(out, p.IPv6Prefix)
	}
	return out, nil
}

func appendPrefix(out []netip.Prefix, raw string) []netip.Prefix {
	if raw == "" {
		return out
	}
	if p, err := netip.ParsePrefix(raw); err == nil {
		return append(out, p.Masked())
	}
	return out
}

func fetchJSON(client *http.Client, url string, v any) error {
	resp, err := client.Get(url)
	if err != nil {
		return err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return fmt.Errorf("status %d", resp.StatusCode)
	}
	return json.NewDecoder(resp.Body).Decode(v)
}
